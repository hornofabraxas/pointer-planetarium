// Writes test/c/sky_cases.h: the phone's answers (attitude.js, astro.js,
// matcher.js) for a spread of inputs, for test/c/sky_test.c to check the
// watch's C port against. Run: node tools/make_sky_cases.js
var fs = require('fs');
var path = require('path');
var A = require('../src/pkjs/astro.js');
var att = require('../src/pkjs/attitude.js');
var matcher = require('../src/pkjs/matcher.js');

var seed = 7;
function rnd() {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed / 2147483648;
}
function r(lo, hi) { return lo + (hi - lo) * rnd(); }
function f(x) { return x.toFixed(6); }

var out = ['// Generated by tools/make_sky_cases.js. Do not edit.', '#pragma once', ''];

// Aims: heading, gravity, wrist, declination, finger -> az, alt.
out.push('static const struct { double head; int16_t ax, ay, az; int wrist; double decl, yaw, pitch, out_az, out_alt; } AIMS[] = {');
for (var i = 0; i < 40; i++) {
  var g = [r(-1, 1), r(-1, 1), r(-1, 0.2)];
  var n = Math.sqrt(g[0] * g[0] + g[1] * g[1] + g[2] * g[2]);
  var acc = { x: Math.round(g[0] / n * 1000), y: Math.round(g[1] / n * 600), z: Math.round(g[2] / n * 1000) };
  var head = r(0, 360), wrist = i % 2, decl = r(-15, 15), yaw = r(-5, 15), pitch = r(-6, 3);
  var d = att.aimDirection(head, acc, wrist, decl, { yaw: yaw, pitch: pitch });
  if (d.rollTooFar) continue;
  out.push('  { ' + [f(head), acc.x, acc.y, acc.z, wrist, f(decl), f(yaw), f(pitch), f(d.az), f(d.alt)].join(', ') + ' },');
}
out.push('};', '');

// Sidereal time and horizon coordinates.
out.push('static const struct { int64_t t; uint16_t ms; double lon, lat, ra, dec, lst, az, alt; } HOR[] = {');
for (i = 0; i < 30; i++) {
  var t = Math.floor(r(1.7e9, 2.1e9)), ms = Math.floor(r(0, 1000));
  var jd = A.julianDay(new Date(t * 1000 + ms));
  var lon = r(-180, 180), lat = r(-60, 70), ra = r(0, 360), dec = r(-80, 85);
  var lst = A.rev(A.gmst(jd) + lon);
  var h = A.eqToHorizon(ra, dec, jd, lat, lon);
  out.push('  { ' + [t, ms, f(lon), f(lat), f(ra), f(dec), f(lst), f(h.az), f(h.alt)].join(', ') + ' },');
}
out.push('};', '');

// Refraction and extinction.
out.push('static const struct { double h, refr, unrefr, ext; } ATMOS[] = {');
[-2, -0.5, 0, 0.5, 1, 2, 5, 10, 20, 30, 45, 60, 89].forEach(function (h) {
  out.push('  { ' + [f(h), f(A.refraction(h)), f(A.unrefract(h)), f(matcher.extinction(h))].join(', ') + ' },');
});
out.push('};', '');

fs.writeFileSync(path.join(__dirname, '..', 'test', 'c', 'sky_cases.h'), out.join('\n'));
console.log('wrote test/c/sky_cases.h');

// ---------------------------------------------------------------- offline answers
// The phone's answers (stars, planets, the Moon only) for aims around a
// few nights and a day, with the ephemeris table the watch would have, for
// test/c/offline_test.c.
var planets = require('../src/pkjs/planets.js');
var moon = require('../src/pkjs/moon.js');
var stars = require('../src/pkjs/stars.js');
var ephem = require('../src/pkjs/ephem.js');

var HERE = { lat: 33.45, lon: -112.07 };
var T0 = new Date('2026-10-09T03:30:00Z');
var eph = ephem.encode(T0, HERE);
var SKIES = ['city', 'suburbs', 'dark'];
var o = ['// Generated by tools/make_sky_cases.js. Do not edit.', '#pragma once', ''];
o.push('static const double HERE_LAT = ' + HERE.lat + ', HERE_LON = ' + HERE.lon + ';');
o.push('static const uint8_t EPH[] = {' + eph.join(',') + '};');
o.push('static const struct { int64_t t; int sky, layer; double az, alt, sigma; const char *l1; int word;',
       '                      const char *l3; } CASES[] = {');
var kept = 0, skipped = 0;
function skyFor(date, setting) {
  var all = planets.bodies(date, HERE.lat, HERE.lon);
  return { jd: A.julianDay(date), lat: HERE.lat, lon: HERE.lon, sunAlt: all[0].alt, sky: setting,
           bodies: all.filter(function (b) { return b.id !== 'uranus' && b.id !== 'neptune'; }),
           moon: moon.moonAltAz(date, HERE.lat, HERE.lon), sats: null, planes: null };
}
var times = [0, 0.4, 1.05, 2.6, 3.1, 4.95].map(function (d) { return new Date(T0.getTime() + d * 86400000); });
times.forEach(function (date, ti) {
  var bright = stars.starsOfDate(A.julianDay(date)).filter(function (s) { return s.mag < 2.5; });
  for (var i = 0; i < 45; i++) {
    var setting = SKIES[i % 3];
    var layer = [0, 3, 4][Math.floor(rnd() * 3)];
    var sky = skyFor(date, setting);
    var az, alt;
    if (i % 3 === 0) {
      az = r(0, 360);
      alt = r(3, 85);
    } else {
      // Near something: a bright star, or the Moon or a planet.
      var tgt;
      if (i % 3 === 1) {
        var s = bright[Math.floor(rnd() * bright.length)];
        var h = A.eqToHorizon(s.ra, s.dec, sky.jd, HERE.lat, HERE.lon);
        tgt = { az: h.az, alt: h.alt + A.refraction(h.alt) };
      } else {
        var bodies = [sky.moon].concat(sky.bodies.slice(1));
        tgt = bodies[Math.floor(rnd() * bodies.length)];
      }
      if (tgt.alt < 3) continue;
      az = A.rev(tgt.az + r(-4, 4));
      alt = Math.min(88, tgt.alt + r(-4, 4));
    }
    var sigma = ti === 3 ? 9 : 4;
    var res = matcher.match({ az: az, alt: alt, sigma: sigma, layer: layer }, sky);
    var c = res.cards.filter(function (x) { return x.type !== matcher.TYPE.SUN; });
    var top = c[0];
    // Too close to call: the two would only differ by rounding.
    var ps = c.map(function (x) { return x.p || 0; });
    var close = ps.length > 1 && ps[0] - ps[1] < 0.06 ||
                [0.75, 0.40, 0.15].some(function (th) { return Math.abs(ps[0] - th) < 0.03; });
    if (close) {
      skipped++;
      continue;
    }
    kept++;
    o.push('  { ' + [Math.floor(date.getTime() / 1000), SKIES.indexOf(setting), layer, f(az), f(alt), sigma,
                     JSON.stringify(top.l1), top.word, JSON.stringify(top.l3)].join(', ') + ' },');
  }
});
o.push('};', '');
fs.writeFileSync(path.join(__dirname, '..', 'test', 'c', 'offline_cases.h'), o.join('\n'));
console.log('wrote test/c/offline_cases.h: ' + kept + ' cases (' + skipped + ' too close to call)');
